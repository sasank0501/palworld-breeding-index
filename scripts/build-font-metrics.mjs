/**
 * Writes src/design/font-metrics.css: the three display faces that sit off-centre in a button,
 * declared again with their ascent and descent adjusted so a capital letter lands in the middle of
 * its line box. Nothing else about the faces changes.
 *
 * Why: a font's own ascent and descent decide where its baseline falls in a line box, and these
 * fonts put the capitals 1 to 2.5 px above the middle at button size (Josefin Sans the most), so a
 * label looked high in every tab and button of that theme. Moving it with a per-button offset would
 * need one for every kind of box; this fixes it once, in Chromium and Firefox. (Safari ignores the
 * two properties and keeps the font's own placement, which is how it was before.)
 *
 * The numbers come from the fonts themselves, measured in a browser at 1000 px: with ascent A,
 * descent D, capital height C (all in em), A + D stays the font's own total and A - D = C puts the
 * middle of the capitals on the middle of the line. Remeasure if a font package is updated
 * (scripts/.cache/home-mock/metrics.mjs does it), then run `node scripts/build-font-metrics.mjs`.
 *
 * Declared again, not edited in place: the @fontsource files stay as the package ships them, and a
 * later @font-face with the same family, weight and range replaces the earlier one.
 */
import fs from 'node:fs';
import path from 'node:path';

const FACES = [
  // family as the package names it, package css files, [ascent-override, descent-override] in percent
  { dir: '@fontsource-variable/oxanium', css: ['wght.css'], metrics: [85.2, 14.8] },
  { dir: '@fontsource-variable/josefin-sans', css: ['wght.css'], metrics: [86.7, 13.3] },
  { dir: '@fontsource/zen-antique', css: ['latin-400.css', 'latin-ext-400.css'], metrics: [109.1, 35.7] },
];

const out = [`/* Generated by scripts/build-font-metrics.mjs: do not edit. See that file for why. */\n`];
for (const { dir, css, metrics } of FACES) {
  for (const file of css) {
    const text = fs.readFileSync(path.join('node_modules', dir, file), 'utf8');
    for (const block of text.match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]*}/g) ?? []) {
      const withPaths = block.replace(/url\(\.\/files\//g, `url(../../node_modules/${dir}/files/`);
      out.push(withPaths.replace(/}\s*$/, `  ascent-override: ${metrics[0]}%;\n  descent-override: ${metrics[1]}%;\n}`) + '\n');
    }
  }
}
fs.writeFileSync('src/design/font-metrics.css', out.join('\n'));
console.log(`wrote src/design/font-metrics.css (${out.length - 1} faces)`);
